
#include <bits/stdc++.h>
using namespace std;

int main() {
    int T;
    cin >> T;

    while (T--) {
        int N, K;
        cin >> N >> K;

        if (K >= (N + 1) / 2 && K <= N)
            cout << "YES" << endl;
        else
            cout << "NO" << endl;
    }

    return 0;
}


